-- changes go through the admin UI (Fitter > Mask Catalog), not new
-- migrations — a catalog that can only be edited by deploying is not a
-- catalog a DME can configure.
--
-- Provenance and the clinical-safety posture
-- -----------------------------------------
-- Model-level facts (manufacturer, model, interface type, size codes,
-- vented vs non-vented, magnetic clips, HCPCS, adult vs pediatric,
-- current vs discontinued) are real and publicly verifiable.
--
-- The facial-geometry BANDS are not. Precise manufacturer fit ranges are
-- proprietary and not reliably published, so each size's band is derived
-- by partitioning the model's overall envelope across its size run and
-- then widening each side by 10% of the bucket width. The widening is
-- deliberate: a too-narrow estimated band produces confident-looking
-- EXCLUSIONS, which is the dangerous direction, whereas a too-wide one
-- merely fails to discriminate.
--
-- Every row therefore lands fit_data_source = 'estimated' and
-- needs_clinical_review = true, and three controls sit on top:
--   1. the recommendation engine caps an unreviewed variant below high
--      confidence, so an estimated band can never produce a confident
--      automated recommendation;
--   2. the fit report prints fit_data_source next to the recommended
--      size, so a clinician knows what the number is worth;
--   3. the whole DB-catalog path is behind fitter.clinical_assessment,
--      seeded OFF (migration 0485).
-- A respiratory therapist clears rows in Fitter > Mask Catalog.
--
-- Which measurements gate a size: nose width, nose-to-chin, and mouth
-- width carry bands here because the source data supports them. Nose
-- height, cheekbone width, and nostril width are left NULL — a NULL band
-- means "this dimension does not gate this size" and the engine skips it
-- rather than inventing a threshold. The engine uses nose height and
-- cheekbone width as scale-plausibility cross-checks feeding measurement
-- confidence instead.
--
-- Idempotent: plain INSERT ... ON CONFLICT DO NOTHING throughout, no
-- DO blocks. This file runs inside railway.json's preDeployCommand and
-- gates the deploy, so it must be safe to re-run on every release.
--
-- Per ADR 003 — versioned hand-authored migration.

